import type { QueryTrace } from './transport';
import { isolateReplaySql } from './replaySql';

type Operation = {method: string; args: any[]; statements: string[]};
type Recipe = {source: string; statements: string[]};
type ViewRecipe = Recipe & {schema?: Record<string,string>};

/** Capture SQL at execution, scoped to adapter operations and concrete View IDs.
 * Internal handler calls bind to the original target, avoiding nested queue deadlocks.
 */
export class ViewSqlCapture {
  private operation?: Operation;
  private queue = Promise.resolve();
  private views = new Map<string, ViewRecipe>();
  private tables = new Map<string, Recipe>();

  get validating() { return this.operation?.method === 'tableDescribe'; }

  record(entry: QueryTrace) {
    if (!entry.error && this.operation) this.operation.statements.push(entry.sql);
  }

  instrument<T extends object>(handler: T): T {
    const wrappers = new Map<PropertyKey, unknown>();
    return new Proxy(handler, {get:(target, property) => {
      const value = Reflect.get(target, property, target);
      if (typeof value !== 'function') return value;
      if (property === 'getFeatures') return value.bind(target);
      if (!wrappers.has(property)) wrappers.set(property, (...args: any[]) => {
        const run = async () => {
          const operation = {method:String(property), args, statements:[] as string[]};
          this.operation = operation;
          try {
            const result = await value.apply(target, args);
            this.commit(operation);
            return result;
          } finally { this.operation = undefined; }
        };
        const result = this.queue.then(run);
        this.queue = result.then(()=>{},()=>{});
        return result;
      });
      return wrappers.get(property);
    }});
  }

  private commit({method,args,statements}: Operation) {
    if (method === 'tableMakeView') {
      const dependency = this.tables.get(args[0]);
      this.views.set(args[1], {
        source:dependency?.source ?? args[0],
        statements:[...(dependency?.statements ?? []), ...statements],
      });
    } else if (method === 'viewMakeTable') {
      const parent = this.views.get(args[0]);
      if (parent) this.tables.set(args[1], {source:parent.source, statements:[...parent.statements,...statements]});
    } else if (['viewExpand','viewCollapse','viewSetDepth'].includes(method)) {
      this.views.get(args[0])?.statements.push(...statements);
    } else if (method === 'viewGetData') {
      const recipe = this.views.get(args[0]);
      if (recipe) recipe.schema = {...args[2]};
    } else if (method === 'viewDelete') this.views.delete(args[0]);
  }

  async snapshot(handler: any, viewId: string, config: any, window: {
    start_row:number; end_row:number; start_col:number; end_col:number;
  }) {
    await this.queue;
    const recipe = this.views.get(viewId);
    if (!recipe) throw new Error('SQL is unavailable for this View; reopen or refresh the source');
    if (!recipe.schema) throw new Error('The View has not fetched data yet');
    // The final full-window SELECT is generated by the same SDK model as data reads.
    // It is not executed here: inspecting SQL must not export the whole dataset.
    const query = handler.sqlBuilder.viewGetData(viewId, config, window, recipe.schema);
    const statements = [...recipe.statements.filter(sql => !/^\s*(?:DESCRIBE|DESC)\b/i.test(sql)),query];
    const replay = isolateReplaySql(statements);
    return {source:recipe.source, viewId, rows:window.end_row, columns:window.end_col, sql:replay.sql, statements:replay.statements};
  }
}
